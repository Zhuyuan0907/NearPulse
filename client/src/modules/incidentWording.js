/**
 * ============================================================================
 * incidentWording.js —— 依事件類型調整的用詞
 * ============================================================================
 * 【為什麼需要這一份】
 * 「我看到他往哪走了」是為了**移動中的加害者**寫的。套到火警上就變成
 * 「火警：我看到他往哪走了」——荒謬，而且會讓人以為系統不知道自己在講什麼。
 *
 * 每一類事件會移動的東西不一樣：
 *   攻擊  加害者會走          → 追蹤的是「人在哪」
 *   火警  煙與火會蔓延        → 追蹤的是「煙在哪」
 *   推擠  壅塞點會轉移        → 追蹤的是「哪裡最擠」
 *   急救  傷者通常不會移動    → 追蹤位置的價值低，但仍需要知道確切位置
 *
 * 追蹤機制（threatMotion）本身完全相同，差別只在**問法**。
 * 問對問題才拿得到答案——恐慌中沒有人會去翻譯一個不對勁的句子。
 */

const WORDING = {
  攻擊: {
    cta: '我看到他往哪走了',
    question: '他現在在哪？',
    hint: '點最接近的出口就好。這會決定其他人的疏散方向要避開哪一邊。',
    repeat: '他移動了就再點一次——可以回報多次。',
    moving: '威脅移動中',
  },
  火警: {
    cta: '我看到煙或火在哪',
    question: '煙或火在哪？',
    hint: '點最接近的出口就好。這會決定其他人要避開哪一邊。',
    repeat: '蔓延了就再點一次——可以回報多次。',
    moving: '火煙擴散中',
  },
  推擠: {
    cta: '我看到哪裡最擠',
    question: '哪裡最擠？',
    hint: '點最接近的出口就好。這會讓其他人改走比較不擠的方向。',
    repeat: '狀況變了就再點一次——可以回報多次。',
    moving: '壅塞點在移動',
  },
  急救: {
    cta: '我知道傷者在哪',
    question: '傷者在哪？',
    hint: '點最接近的出口就好。這會讓趕來協助的人少找幾分鐘。',
    repeat: '位置變了就再點一次。',
    moving: '位置有變動',
  },
};

const FALLBACK = {
  cta: '我知道確切位置在哪',
  question: '狀況在哪裡？',
  hint: '點最接近的出口就好。這會讓其他人知道該避開哪一邊。',
  repeat: '狀況變了就再點一次——可以回報多次。',
  moving: '位置在移動',
};

export function wordingFor(typeLabel) {
  return WORDING[typeLabel] ?? FALLBACK;
}
